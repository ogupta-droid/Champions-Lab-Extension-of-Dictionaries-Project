# Store each team's calculated points so option 6 can use them
team_points = {}

def power_rankings():
  # Remove old scores before calculating the rankings again
  team_points.clear()
  rankingsbase = []
  for team, stats in champions_league.items():
    # Start each team's score at zero
    score = 0
    for stat, value in stats.items():
      # Skip country because it is text instead of a number
      if stat != "country":
        if stat == "losses":
          # Subtract 2 points for each loss
          score = score - (value * 2)
        elif stat == "wins":
          # Add 10 points for each win
          score = score + (value * 10)
        elif stat == "draws":
          # Add 3 points for each draw
          score = score + (value * 3)
        elif stat == "goals":
          # Add 4 points for each goal
          score = score + (value * 4)
        elif stat == "sot":
          # Add 1 point for each shot on target
          score = score + value
        elif stat == "conversion_rate":
          # Add 0.5 points for each percentage point of conversion rate
          score = score + (value * 0.5)
        elif stat == "pass_accuracy":
          # Add 0.2 points for each percentage point of pass accuracy
          score = score + (value * 0.2)
        elif stat == "clean_sheets":
          # Add 5 points for each clean sheet
          score = score + (value * 5)
        elif stat == "saves":
          # Add 1 point for each save
          score = score + value
        elif stat == "defensive_tackles":
          # Add 0.5 points for each defensive tackle
          score = score + (value * 0.5) # all of the if, elif statements above are taking all of the stats that I have collected and based off of values that I have assigned
    # Save the team's total score for option 6
    team_points[team] = score
    # Add the team and its score to the list that will be sorted
    rankingsbase.append((team, score))
  rankingsbase.sort(key=lambda x: x[1], reverse=True) #looked this up to learn how to sort my list from greatest to least
  # Start the rankings at number 1
  rank = 1
  for team, score in rankingsbase:
    print(f"Ranked #{rank} is {team} with {score} points")
    rank = rank + 1 #This is cycling through for the next team so it doesnt repeat the same number

def best_country():
    # Check whether option 5 has saved any team scores
    if len(team_points) == 0:
        print("Please run option 5 first")
        return # stopping the function but keeping the while True going looked up

    # Store each country's total points and number of teams separately
    country_points = {}
    country_teams = {}

    for team, points in team_points.items():
        country = champions_league[team]["country"]

        if country not in country_points:
            # Start the totals at zero when a country first appears
            country_points[country] = 0
            country_teams[country] = 0

        # Add this team's score to its country's total points
        country_points[country] += points
        # Count one more team for this country
        country_teams[country] += 1

    # Start without a winning country and with a score of zero
    best = ""
    best_score = 0

    for country in country_points:
        # Divide the country's total points by its number of teams
        average = country_points[country] / country_teams[country] #This is finding the average points per country
        bonus = country_teams[country] * 5 #This is adding a bonus for each team becuase I found that there was a mid team that was unique to 1 country but England just had 1 bad team so this adds a bonus for the amount of teams there are
        score = average + bonus #This adds the average and the bonus

        if best == "" or score > best_score: #If the newest value being compared is higher than the previous highest it is the new highest
            # Save the winning country's name and its score including the bonus
            best = country
            best_score = score

    print("Best country:", best)
    # Round the winning score to two decimal places for display
    print("Score including team bonus:", round(best_score, 2))


